export type IconName = keyof typeof formas;

/** Tamanhos que o CSS global já prevê (.i13, .i16, .i18, .i22, .i24). */
export type IconSize = 13 | 16 | 18 | 22 | 24;

interface IconProps {
  name: IconName;
  size?: IconSize;
  /** Preenche a forma (ex.: ícone de play). */
  fill?: boolean;
  className?: string;
  style?: CSSProperties;
}

export function Icon({ name, size, fill, className, style }: IconProps) {
  return (
    <svg
      className={cx("i", size && `i${size}`, fill && "fill", className)}
      style={style}
      aria-hidden="true"
    >
      <use href={`#i-${name}`} />
    </svg>
  );
}

/** Sprite com todos os símbolos; deve ser renderizado uma vez no layout raiz. */
export function IconSprite() {
  return (
    <svg width="0" height="0" style={{ position: "absolute" }} aria-hidden="true">
      {(Object.keys(formas) as IconName[]).map((nome) => (
        <symbol key={nome} id={`i-${nome}`} viewBox="0 0 24 24">
          {formas[nome]}
        </symbol>
      ))}
    </svg>
  );
}
